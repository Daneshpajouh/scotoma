#!/usr/bin/env python3
"""Seal and verify the complete deposited artifact set, including the findings."""
import sys
sys.dont_write_bytecode=True
from pathlib import Path
HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE))
from integrity import sha,require
import argparse


def files():
    paths=[p for p in HERE.rglob('*') if p.is_file() and not p.is_symlink() and
           p.name!='SHA256SUMS' and
           not {'verify_work','changed_input'} & set(p.relative_to(HERE).parts) and
           p.relative_to(HERE).as_posix()!='results/verification.json']
# 2026-11-02: changed_input joins verify_work as excluded. Both are GENERATED by running the
# checks, so including them made the seal valid only on a pristine tree: the first run passed,
# created changed_input, and the second run failed with "Artifact file set differs". A seal that
# breaks because someone ran the checks is a seal that gets ignored. results/verification.json is
# excluded for the same reason and no other: it is the run receipt, carrying that run's wall clock
# and peak resident memory, and it was measured to be the ONLY file a replay rewrites. Sealing a
# file that the act of checking regenerates proves nothing; the replay that rewrites it IS the
# check, and its own exit code is the evidence.
    return sorted(paths+[HERE.parent/'FINDINGS.md'])


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    action=parser.add_mutually_exclusive_group(required=True)
    action.add_argument('--write',action='store_true')
    action.add_argument('--verify',action='store_true')
    args=parser.parse_args()
    def relative(p):
        return '../FINDINGS.md' if p==HERE.parent/'FINDINGS.md' else str(p.relative_to(HERE))
    if args.write:
        (HERE/'SHA256SUMS').write_text(''.join(sha(p)+'  '+relative(p)+'\n' for p in files()))
        print('Artifact SHA-256 seal written.')
    else:
        rows=[line.split('  ',1) for line in (HERE/'SHA256SUMS').read_text().splitlines()]
        require({name for _,name in rows}=={relative(p) for p in files()},'Artifact file set differs')
        for digest,name in rows:
            require(sha(HERE/name)==digest,'Artifact SHA-256 mismatch: '+name)
        print('ARTIFACT_SEAL_EXIT_CODE=0')


if __name__=='__main__':
    main()
